# merge_and_rebuild_bank.py
# Merges existing questions.json with new verified questions, generates reinforcement questions for all,
# and outputs questions.json and questions_data.js.

import json
import os
from build_full_portal_bank import make_reinforcement

WEB_APP_DIR = r"c:\Users\acer\Desktop\Automation\etc files\web_app"
ORIG_JSON = os.path.join(WEB_APP_DIR, "questions.json")
NEW_JSON = os.path.join(WEB_APP_DIR, "all_new_questions.json")
OUTPUT_JSON = os.path.join(WEB_APP_DIR, "questions.json")
OUTPUT_JS = os.path.join(WEB_APP_DIR, "questions_data.js")

with open(ORIG_JSON, 'r', encoding='utf-8') as f:
    existing_questions = json.load(f)

with open(NEW_JSON, 'r', encoding='utf-8') as f:
    new_questions = json.load(f)

print(f"Loaded {len(existing_questions)} existing questions and {len(new_questions)} new questions.")

# Standardize and add reinforcementQuestion to existing questions
for q in existing_questions:
    if 'reinforcementQuestion' not in q or not q['reinforcementQuestion']:
        q['reinforcementQuestion'] = make_reinforcement(q)
    # Ensure options structure is clean
    for opt in q.get('options', []):
        opt['text'] = opt['text'].strip()

# Combine both sets, checking for duplicate IDs
used_ids = set()
all_merged = []

for q in existing_questions:
    qid = q.get('id')
    used_ids.add(qid)
    all_merged.append(q)

for q in new_questions:
    qid = q.get('id')
    if qid in used_ids:
        qid = f"{qid}_NEW"
        q['id'] = qid
    used_ids.add(qid)
    # Ensure reinforcementQuestion exists
    if 'reinforcementQuestion' not in q or not q['reinforcementQuestion']:
        q['reinforcementQuestion'] = make_reinforcement(q)
    all_merged.append(q)

print(f"Total merged questions: {len(all_merged)}")

# Statistics
topics_count = {}
sources_count = {}
for q in all_merged:
    top = q.get('topic', 'Unassigned')
    src = q.get('sourceFile', 'Unknown')
    topics_count[top] = topics_count.get(top, 0) + 1
    sources_count[src] = sources_count.get(src, 0) + 1

print("\n--- Question Counts by Topic ---")
for t, c in sorted(topics_count.items()):
    print(f"  {t}: {c}")

print("\n--- Question Counts by Source File ---")
for s, c in sorted(sources_count.items()):
    print(f"  {s}: {c}")

# Save JSON
with open(OUTPUT_JSON, 'w', encoding='utf-8') as f:
    json.dump(all_merged, f, indent=2, ensure_ascii=False)

# Save JS
js_content = "// Autogenerated ISE 291 Master Question Bank Data\n"
js_content += "window.QUESTIONS_DATA = " + json.dumps(all_merged, ensure_ascii=False) + ";\n"
js_content += "window.QUESTION_BANK = window.QUESTIONS_DATA;\n"

with open(OUTPUT_JS, 'w', encoding='utf-8') as f:
    f.write(js_content)

print(f"\nSuccessfully generated {OUTPUT_JSON} and {OUTPUT_JS} ({os.path.getsize(OUTPUT_JS)} bytes).")
